// CustomEncryptor.swift
// iOS integration for custom AES-256-GCM encryption in S3BgUploader.
//
// This file demonstrates how to register a custom encryptor from Swift.
// The Rust library is statically linked into your app binary.

import Foundation

// FFI types matching the Rust side
private struct EncryptResult: OpaquePointer {
    var data: UnsafeMutablePointer<UInt8>
    var len: UInt
    var capacity: UInt
}

private struct EncryptorVTable: OpaquePointer {
    var version: UInt32
    var encrypt_chunk: UnsafeMutableRawPointer
    var free: UnsafeMutableRawPointer
    var destroy: UnsafeMutableRawPointer
}

// ---------------------------------------------------------------------------
// External C functions from the Rust library
// ---------------------------------------------------------------------------

// These are declared in the Rust library's header (generated by cbindgen).
// The header should be included in your Xcode project.
@_silgen_name("custom_encryptor_register")
func custom_encryptor_register(
    keyHex: UnsafePointer<CChar>?,
    nonceHex: UnsafePointer<CChar>?
)

// ---------------------------------------------------------------------------
// Swift API
// ---------------------------------------------------------------------------

/// Register a custom AES-256-GCM encryptor with S3BgUploader.
///
/// Call this once at app startup, before any uploads.
///
/// - Parameters:
///   - keyHex: 64 hex characters (32 bytes) — the AES-256 key.
///   - nonceHex: 48 hex characters (24 bytes) — the base nonce.
///
/// - Example:
///   ```swift
///   CustomEncryptor.register(
///       keyHex: "deadbeefdeadbeefdeadbeefdeadbeefdeadbeefdeadbeefdeadbeefdeadbeef",
///       nonceHex: "cafebabecafebabecafebabecafebabecafebabecafebabe"
///   )
///   ```
@objc(CustomEncryptor)
public class CustomEncryptor: NSObject {

    @objc(registerKeyHex:nonceHex:)
    public static func register(keyHex: String, nonceHex: String) {
        keyHex.withCString { keyPtr in
            nonceHex.withCString { noncePtr in
                custom_encryptor_register(keyHex: keyPtr, nonceHex: noncePtr)
            }
        }
    }

    /// Register with pre-computed key/nonce bytes.
    @objc(registerKey:nonce:)
    public static func register(key: [UInt8], nonce: [UInt8]) {
        let keyHex = key.map { String(format: "%02x", $0) }.joined()
        let nonceHex = nonce.map { String(format: "%02x", $0) }.joined()
        register(keyHex: keyHex, nonceHex: nonceHex)
    }
}
